function subscribeLanguage(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener("mawj-language-change", onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener("mawj-language-change", onChange);
  };
}

function getSavedLanguage(): Language {
  return window.localStorage.getItem("mawj-language") === "ar" ? "ar" : "en";
}

function getServerLanguage(): Language { return "en"; }

type Dictionary = { [Key in keyof typeof strings.en]: string };
type LanguageContextValue = { language: Language; setLanguage: (language: Language) => void; t: Dictionary };
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const language = useSyncExternalStore(subscribeLanguage, getSavedLanguage, getServerLanguage);
  const setLanguage = useCallback((nextLanguage: Language) => {
    window.localStorage.setItem("mawj-language", nextLanguage);
    window.dispatchEvent(new Event("mawj-language-change"));
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, t: strings[language] }), [language, setLanguage]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
